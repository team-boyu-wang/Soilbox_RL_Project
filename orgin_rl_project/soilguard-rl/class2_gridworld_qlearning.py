# %% 1-1　★把"判据"写成代码：train + rollout_greedy + evaluate_seeds
# 【这段做什么】定义三个函数，构成"训练→评估→量化"的判据流水线：
#   · train(eps, alpha, episodes, seed)：跑 Q-learning，返回学好的 Q 表。★更新就是讲稿那一行公式。
#   · rollout_greedy(Q)：拿学好的 Q 纯贪心跑一局（部署时不再探索），返回 (结局, 回报, 路径)。
#   · evaluate_seeds(eps, ...)：跑 n 个随机种子，返回(到水井成功率, 平均回报)——单次有运气，多 seed 才可信。
#
# 【train 里的 Q-learning 核心逻辑（对应讲稿 Slide 13 更新公式）】
#   Q 表初始化全 0——智能体对迷宫完全无知，每个(状态, 动作)对的"未来期望回报"都估为 0。
#   每步做完动作 a（从 s 走到 s2，拿到奖励 r）之后，更新这一步的 Q 值：
#     target = r + γ × max_a' Q[s2, a']   （"这步我实际拿了 r，加上从 s2 出发最好能拿多少"）
#     Q[s, a] ← Q[s, a] + α × (target − Q[s, a])   （朝"实际更好"的方向挪 α 那么多）
#   括号里的 (target − Q[s,a]) 叫"TD 误差"（Temporal Difference Error）。
#   直觉：就像你每天预测明天天气的分数，然后和真实结果对账，一点点修正自己的直觉。
#   终止步（done=True）时：s2 是终止状态，没有"从 s2 出发的未来"，所以 maxQ'=0，
#     target = r + 0 = r（纯拿到的即时奖励，不再打折）。代码里"0.0 if done else ..."就是这个逻辑。
#
# 【rollout_greedy 和 train 里策略的区别】
#   train 里用 ε-greedy（训练时带探索）；rollout_greedy 是纯贪心（部署时不再随机，代表"学到的策略"）。
#   这个分离很重要：训练时探索是为了"收集更多样的经验"，部署时贪心是"把学到的最好知识展示出来"。
#
# 【为什么要函数化、为什么多 seed】
#   "它学没学会"不能靠跑一次拍脑袋——随机种子不同，初始动作序列不同，结果可能差很多。
#   写成判据函数、跑 30 个种子取平均，ε=0 和 ε>0 才有可比的硬数字。
#   这和 GeoTongue L1 "判据要量化、别自己骗自己"是同一条纪律：单次实验不算数，要统计。
#
# 【看什么】这段只定义函数，不出数字；下面 1-2 才真正调用它们出结果。
def train(eps, alpha=0.5, episodes=300, seed=0, c=CONFIG):
    """Q-learning 训练，返回 Q 表。eps=探索率(0=纯贪心)。"""
    rng = np.random.RandomState(seed); env = GridWorld(c)
    Q = np.zeros((env.nS, env.nA))                          # ★一开始全 0：纯瞎猜
    for _ in range(episodes):
        s = env.reset(); done = False
        while not done:
            # ε-greedy：eps 概率随机探索，否则贪心选 Q 最大（ε=0 就是纯贪心）
            a = rng.randint(env.nA) if rng.rand() < eps else int(np.argmax(Q[s]))
            s2, r, done, _ = env.step(a)
            # ★Q-learning 更新（讲稿那一行）：终止时没有未来，maxQ' 当 0
            target = r + (0.0 if done else c["gamma"] * np.max(Q[s2]))
            Q[s, a] += alpha * (target - Q[s, a])           # 朝误差方向挪一小步
            s = s2
    return Q

def rollout_greedy(Q, c=CONFIG):
    """拿学好的 Q 纯贪心跑一局（部署时不再探索），返回 (结局, 回报, 路径)。"""
    env = GridWorld(c); s = env.reset(); done = False; G = 0.0; info = None; path = [env.pos]
    while not done:
        a = int(np.argmax(Q[s])); s, r, done, info = env.step(a); G += r; path.append(env.pos)
    return info, G, path

def evaluate_seeds(eps, alpha=0.5, episodes=300, n_seed=30, c=CONFIG):
    """判据：跑 n_seed 个种子，返回 (到水井成功率, 平均回报)。这是量化'学得多好'的硬尺子。"""
    goals = 0; Gs = []
    for seed in range(n_seed):
        Q = train(eps, alpha, episodes, seed, c)
        outcome, G, _ = rollout_greedy(Q, c)
        goals += (outcome == "goal"); Gs.append(G)
    return goals / n_seed, float(np.mean(Gs))

print("判据流水线就绪：train(训练) + rollout_greedy(贪心跑一局) + evaluate_seeds(多 seed 量化)")

# %% 1-2　纯贪心 ε=0 训练 30 seed → 看它瘫痪
# 【这段做什么】用 ε=0（纯贪心，只利用不探索）训练 30 个不同随机种子，统计到水井成功率和平均回报。
# 【ε=0 的含义】train() 里"rng.rand() < eps"这个条件永远为 False（eps=0），
#   所以每步都执行贪心：a = int(np.argmax(Q[s]))——每步选 Q 值最大的那个动作。
#   全 0 的 Q 表，argmax 永远返回 0（"上"），于是 30 个种子跑出来的路径是完全一样的。
#   这就是"没有随机性 → 没有探索 → 只走一条路"的直接后果。
#
# 【预期（服务器实测）】成功率 0/30、平均回报 0.00。
#   它【一次都没到过水井】——整张 Q 表从第一局到第 300 局几乎纹丝不动。
#   为什么整张表不动？撞墙时奖励 r=0，s2=s（原地），target = 0 + γ×max(Q[s])=0，
#   Q[s,a] 更新 = Q[s,a] + α×(0 - 0) = Q[s,a]，即不变。这就是死循环的数学闭环。
#
# 【看什么】成功率是不是 0%、回报是不是 0.00。
#   注意：多跑几个 seed 也没用，它们都走同一条死路（全 0 表 + ε=0 = 零随机性）。
