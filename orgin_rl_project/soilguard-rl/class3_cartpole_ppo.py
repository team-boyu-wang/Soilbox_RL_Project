# %% 5　标准 vs 域随机化，杆长扫描两条线
# 【这段做什么】把实验 2-1（标准模型，红线）和 4-2（域随机化模型，绿线）两条曲线
#   画在同一张图上，做"鲁棒性对照图"。数据已经在前面的实验里算好了，这里只是可视化。
#   另外加两条参考线：竖虚线标出训练时用的杆长（length=0.5），横虚线标出满分线（500）。
#
# 【看什么】
#   · 红线（标准模型）：在 length≤0.75 时贴着满分线，到 length=1.0 开始断崖跳水，
#     之后就趴在低位——这条线的形状就是"过拟合"的曲线特征：在训练点附近好，离开就崩。
#   · 绿线（域随机化模型）：全程贴着 500，从最短 0.25 到最长 2.0，一个点都没掉下去——
#     这条线的形状就是"鲁棒性"：在整个测试范围内都保持高性能。
#   · 竖虚线（length=0.5）就是训练点：红线的"好区域"以它为中心，往外走就崩了。
#     绿线对这条竖线毫不在乎——它哪儿都行。
#
# 【为什么这张图是 sim-to-real 类课题论文里最有说服力的一张】
#   这张图的横轴是"部署时可能遇到的世界参数范围"，纵轴是"在那个世界里的表现"。
#   你用一张图就回答了一个部署最关心的问题：
#   "这个模型在参数偏离训练设置多远的情况下还能用？"
#   红线的答案：几乎不能偏。绿线的答案：0.25~2.0 都能用。
#   这才是"能不能部署"的真正依据——不是训练曲线好不好看，而是鲁棒性曲线有多宽。
#
# 【科研评估闭环】
#   · 判据（撑多少步）告诉你"在某一点好不好"；
#   · 鲁棒性曲线告诉你"在多大范围内好"——也叫"泛化范围"或"鲁棒区间"；
#   · 后者才是部署敢不敢用的依据。
#   一个只在训练点满分的模型（单点峰值），和一个在整段区间都满分的模型（宽泛化），
#   前者在仿真里"更好看"，后者在现实里"更能用"。这就是泛化性/鲁棒性比峰值更重要的原因。
#   Class 3 的核心一句话，用这张图就说清了。
