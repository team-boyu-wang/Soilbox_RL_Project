# %% 4-1　域随机化训练（每局随机杆长）
# 【这段做什么】对症下药——重新训一个 PPO，但这次训练时每一局开始都随机换一个杆长，
#   范围从最短 0.25 到最长 2.0。其它参数不变（重力/杆重/推力默认，无额外噪声）。
#   这就是"域随机化（domain randomization）"：在训练里主动引入参数随机性。
#
# 【域随机化的核心思想——为什么这样能救泛化】
#   病根是"只见过一种世界（length=0.5）"，那就让它训练时见过整个杆长范围的世界。
#   当每局杆长都不一样，"死记 length=0.5 的节奏"就没有任何用了——
#   它必须学一个对任何杆长都管用的平衡策略，也就是"更通用的平衡规律"。
#   训练时见过 0.25 到 2.0 的各种杆，测试时遇到任何杆长都不陌生。
#   就像让学生练各种数字版本的题（不只练 x=2 的情况），自然就能应对任何 x。
#
# 【为什么域随机化是 sim-to-real 最主流的救法】
#   真实世界里，你没办法精确知道部署时的参数是多少（土箱的土质每次装都不同、
#   探头老化后参数漂移……）。既然无法精确知道，就用"覆盖一个范围"来代替
#   "精确匹配"：把可能出现的参数范围都在训练里随机到了，部署时不管来的是哪个，
#   模型都见过接近的情况，就能扛住。这是工程实用性最强的泛化策略之一。
#
# 【为什么训 100000 步而不是 50000 步】
#   域随机化任务比标准任务难：每局杆长都不一样，智能体需要"同时学会应付各种杆"，
#   本质上是在学一个更复杂的函数（输入不只是当前观测，还隐含了当前杆长的信息）。
#   更难的任务需要更多的经历才能收敛，所以步数加倍。
#
# 【预期（服务器实测）】
#   域随机化训练完成后，标准环境测 500.0——见多识广没有牺牲标准世界的峰值。
#   这很重要：域随机化救泛化，但没有牺牲原来的满分。两全其美。
#
# 【看什么】这段会训练一段时间（比标准多，约需更多分钟），
#   等它跑完、看 dr_on_std 输出。如果仍然 500.0，就准备好看实验 4-2 的并排对比了。
dr_model, dr_log = train_ppo(
    (lambda: TweakCartPole(randomize_length=True, length_range=(0.25, 2.0))),
    100000, "域随机化（每局随机杆长）")
dr_on_std = evaluate(dr_model, make_standard)
print("实验 4-1：域随机化模型训练完成")
print(f"  它在标准世界：{dr_on_std:.1f} 步（服务器实测 500.0）——见多识广没牺牲标准世界的峰值。")

# %% 4-2　域随机化模型 vs 标准模型在各杆长下对比 → 救回
# 【这段做什么】用实验 2-1 完全相同的判据，在完全相同的 6 个杆长（0.25/0.5/0.75/1.0/1.5/2.0）
#   下，测域随机化模型的成绩，并和标准模型并排打印对比表。
#
# 【控制变量：为什么这个对比是干净的】
#   两个模型用同一把判据（evaluate）、同一组初始 seed（2000+ep）、同一组杆长，
#   任何成绩差异只来自"训练时有没有做域随机化"——这才是干净的对比。
#   如果评估方式不一样（比如标准用 10 局，域随机化用 100 局），就没有可比性了。
#
# 【预期（服务器实测）】
#   域随机化模型：杆长 0.25~2.0 全部 500.0
#   对比标准模型：1.0 只有 83.6、1.5 只有 16.4、2.0 只有 19.0
#   救回得干干净净——同样的长杆世界，标准模型十几分、域随机化模型满分。
#
# 【看什么】
#   · 并排对比表里，标准模型从 length=1.0 开始就有显眼的低分；
#     域随机化模型那一列全是 500.0。
#   · 特别看 length=1.5 那行：标准 16.4 vs 域随机化 500.0，差距约 30 倍。
#   · 这就是"救回"的铁证。域随机化没有牺牲短杆的成绩（两者在短杆上都 500），
#     只是让长杆的成绩从崩了救回来——这叫"以更多训练换取更广泛化"。
#
# 【到这里，实验的完整逻辑链合拢了】
#   满分（实验1）→ 换个世界就崩（实验2）→ 诊断是过拟合（实验3）→ 域随机化救回（实验4）
#   每一步都是有证据的推进，而不是凭直觉的跳跃。第5部分把这两条曲线画出来，
#   让"救没救回"的结论一目了然。
print("实验 4-2：域随机化模型 vs 标准模型（各杆长并排对比）")
dr_by_len = []
for L in lengths:
    s = evaluate(dr_model, (lambda L=L: make_tweaked(length=L)))
    dr_by_len.append(s)
print(f"  {'杆长':<8}{'标准模型':<12}{'域随机化模型':<12}")
for L, a, b in zip(lengths, std_by_len, dr_by_len):
    print(f"  {L:<8}{a:<12.1f}{b:<12.1f}")
print("  →（服务器实测域随机化全 500）同样的长杆世界，标准模型十几分、域随机化模型满分。救回。")

