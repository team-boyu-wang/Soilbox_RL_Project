# %% 0-2　可调 CartPole（能改杆长/噪声、能域随机化）
# 【这段做什么】写一个 CartPole 的"可调版"包装器（TweakCartPole），让我们能：
#   ① 改物理参数（杆长 length / 重力 gravity / 杆重 masspole / 推力 force_mag）；
#   ② 给观测加高斯噪声（模拟真实传感器不准——这正是 sim-to-real 里的"传感器噪声"坎）；
#   ③ 域随机化（训练时每一局开始前随机抽一个杆长）——这是实验 4 的救命工具。
#
# 【为什么要自己写包装器，不直接用 gym 的 CartPole】
#   gym 现成的 CartPole 物理参数是在代码里写死的（length=0.5、gravity=9.8……）。
#   但我们研究的核心问题是"换个世界还能不能用"——所以必须能【主动改变这个世界】。
#   包装器（Wrapper）是 gym 的标准玩法：继承 gym.Wrapper，在 reset/step 里做一点额外处理，
#   对外接口不变（算法看到的还是正常的 env），但内部世界已经变了。
#   就像给一部车换了发动机，外壳还是那个外壳，方向盘/油门/刹车用法不变。
#
# 【关键技术点：为什么 apply_params 必须重算两个派生量】
#   CartPole 物理引擎内部有两个"派生量"：
#     · total_mass = masscart + masspole（系统总质量，影响加速度计算）
#     · polemass_length = masspole × length（杆的角加速度分母）
#   这两个量在 gym 初始化时算好并缓存。如果你直接改 length 而不重算它们，
#   物理引擎用的还是旧的缓存值——相当于"改了杆长但引擎还按旧杆长算"，
#   实验结果就是假的。apply_params 做的就是"改完同步重算派生量"这件事。
#
# 【域随机化（domain randomization）原理先简介】
#   域随机化 = 训练时每一局开始前，随机改变世界的某个参数（这里是杆长）。
#   智能体每局面对不同的杆，不得不学一个"对各种杆都管用"的策略，
#   而不是只背"这根杆的应对"。就像让学生做题时每道题数字都不一样，
#   就不能靠背答案，只能真正搞懂方法。这是 sim-to-real 领域最主流的泛化增强手段。
#
# 【观测噪声模拟的是什么】
#   CartPole 标准观测有 4 个维度：小车位置、小车速度、杆角度、杆角速度。
#   仿真里这四个值是精确的，真实传感器（编码器/陀螺仪）读出来会有随机误差。
#   我们用 np.random.normal(0, obs_noise) 在每个维度加高斯噪声来模拟。
#   obs_noise=0.2 的意思是：每个观测值都会叠加一个标准差为 0.2 的随机误差。
#   这跟你的土箱项目里"电化学探头读数带基线漂移和随机噪声"是同一个问题。
#
# 【看什么】代码里没有 print，这段只是"造工具"。但要记住：
#   make_tweaked(length=1.5) 造的就是"杆长 1.5 的扰动世界"，
#   make_tweaked(obs_noise=0.2) 造的就是"传感器误差 0.2 的扰动世界"。
#   后面所有实验都用这个工具，记住它能"主动造世界"这个能力。
import numpy as np
import matplotlib.pyplot as plt
import gymnasium as gym
from stable_baselines3 import PPO
from stable_baselines3.common.monitor import Monitor
from stable_baselines3.common.callbacks import BaseCallback
plt.rcParams["axes.unicode_minus"] = False

SEED = 42
np.random.seed(SEED)
BASE = dict(length=0.5, masspole=0.1, gravity=9.8, force_mag=10.0)   # CartPole 出厂默认值

def apply_params(env, p):
    """把一组物理参数写进 CartPole，并重算派生量。"""
    u = env.unwrapped
    u.length = p["length"]; u.masspole = p["masspole"]
    u.gravity = p["gravity"]; u.force_mag = p["force_mag"]
    u.total_mass = u.masspole + u.masscart            # 派生量，必须重算
    u.polemass_length = u.masspole * u.length         # 派生量，必须重算

class TweakCartPole(gym.Wrapper):
    """可调物理参数 + 可选观测噪声 + 可选域随机化（随机杆长）的 CartPole。"""
    def __init__(self, params=None, obs_noise=0.0, randomize_length=False, length_range=(0.25, 2.0)):
        super().__init__(gym.make("CartPole-v1"))
        self.params = dict(BASE, **(params or {}))    # 没指定的参数用默认值
        self.obs_noise = obs_noise                    # 观测噪声标准差（0 = 无噪声）
        self.randomize_length = randomize_length      # 训练时是否每局随机杆长
        self.length_range = length_range
        self._rng = np.random.RandomState(SEED)
        apply_params(self.env, self.params)
    def reset(self, **kw):
        if self.randomize_length:                     # 域随机化：每局开局随机抽一个杆长
            p = dict(self.params); p["length"] = self._rng.uniform(*self.length_range)
            apply_params(self.env, p)
        obs, info = self.env.reset(**kw)
        return self._noisy(obs), info
    def step(self, a):
        obs, r, term, trunc, info = self.env.step(a)
        return self._noisy(obs), r, term, trunc, info
    def _noisy(self, obs):
        if self.obs_noise > 0:                        # 给观测加高斯噪声，模拟真实传感器
            obs = (obs + self._rng.normal(0, self.obs_noise, size=obs.shape)).astype(np.float32)
        return obs

