# %% 2-3　对照：改重力/杆重/推力 → 全 500（分清哪些扰动致命）
# 【这段做什么】刚才看到了两种"会害死模型"的扰动（杆长、噪声）。
#   但如果我们就此下结论说"模型一受扰动就崩"，那就错了——这个结论太宽泛，没有价值。
#   所以这一组测三个"PPO 扛得住"的扰动：重力（gravity）、杆重（masspole）、推力（force_mag）。
#   用来做对照：证明 PPO 不是"一扰动就崩"，而是对某些扰动鲁棒、对某些不行——
#   分清楚哪些"致命"、哪些"无所谓"，才能给出有研究价值的结论。
#
# 【为什么 PPO 对这三个扛得住——直觉】
#   重力/杆重/推力的变化，本质上是对整个动力学做了一个"等比例缩放"——
#   重力加倍、杆重加倍，但平衡的"节奏"（什么时候该推、推多少）并没有本质改变，
#   只是力度的量级变了。神经网络的策略在量级上有一定容忍度，所以扛得住。
#   但杆长改变的是"平衡点的空间结构"——短杆和长杆平衡时需要的推力节奏根本就不一样，
#   不是"量级"的差异，是"质"的差异。神经网络跨不过这个"质变"。
#   噪声类似：它污染了神经网络"认路"用的观测，而不是改变了力学响应。
#
# 【预期（服务器实测）】
#   重力 5~30 全 500 / 杆重 masspole 0.1~1.0 全 500 / 推力 force 2~20 全 500
#   PPO 对这三个参数的大幅扰动都扛住了——满分一个没掉。
#
# 【为什么这组对照极重要：它是研究能力的体现】
#   如果你实验 2 只做了 2-1 和 2-2，你只能说"模型对某些扰动垮了"。
#   加上 2-3 这组对照，你能说的是：
#     "PPO 对结构性变化（杆长）和观测污染（传感器噪声）敏感，
#      但对动力学参数的量级变化（重力/杆重/推力）具有较强鲁棒性。"
#   这是一句精确的结论，不是宽泛的断言。
#   能分清"哪些扰动致命、哪些无所谓"，本身就是研究里很有价值的判断——
#   它告诉你：部署时该重点担心什么（结构差异、传感器噪声），不必过度担心什么（动力学缩放）。
#
# 【看什么】每行输出都没有"← 崩了"——全 500。
#   对比上两组（杆长/噪声全崩），这个对比就是"分类扰动"的核心实验结果。
print("实验 2-3：对照组——改重力/杆重/推力（看是不是'一扰动就崩'）")
for g in [5, 20, 30]:
    s = evaluate(std_model, (lambda g=g: TweakCartPole({"gravity": g})))
    print(f"  重力 gravity={g:<3} 平均撑 {s:6.1f} 步")
for mp in [0.5, 1.0]:
    s = evaluate(std_model, (lambda mp=mp: TweakCartPole({"masspole": mp})))
    print(f"  杆重 masspole={mp:<4} 平均撑 {s:6.1f} 步")
for fm in [2, 20]:
    s = evaluate(std_model, (lambda fm=fm: TweakCartPole({"force_mag": fm})))
    print(f"  推力 force_mag={fm:<3} 平均撑 {s:6.1f} 步")
print("  →（服务器实测全 500）不是'一扰动就崩'：它扛得住动力学缩放，只栽在'杆长'和'噪声'上。")
print("    研究判断：部署时重点防'结构差异 + 传感器噪声'，这就是下一步要救的方向。")

