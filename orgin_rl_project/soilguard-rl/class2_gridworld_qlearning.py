# %% 0-2　网格世界配置（最终迷宫 + 为什么这么设计）
# 【这段做什么】把整节实验的迷宫和所有超参集中在 CONFIG 字典里，后面所有实验都从这套配置出发。
#   这是控制变量原则的体现：配置写在一处，后面改任何一项都只在这里改，不会漏改某个函数。
#
# 【迷宫为什么这么设计（关键，最好先想一想再往下看）】
#   起点 (4,0) 在左下角，水井 (0,4) 在右上角——它们在对角线上，要到水井必须【先一路向上、再向右拐】。
#   这条路径有一个"拐点"：不能一路到底，必须在某个格子选择转向右。
#   而一张全 0 的 Q 表，每个状态的所有动作 Q 值全是 0，argmax(Q[s]) 永远返回下标最小的动作——
#   这里动作 0 是"上"——所以纯贪心(ε=0)从起点出发会【一路向上、撞死在左上角】，
#   永远学不会那个关键的"右拐"。这就是贪心陷阱埋的雷，实验 1 你会亲眼看到这条死路。
#
# 【各超参的含义】
#   · max_steps=50：一局最多走 50 步，防止它原地打圈。纯贪心死局每步都在撞墙，50 步后强制结束（结局="timeout"）。
#   · gamma=0.9：折扣因子。8 步外的 +10 水井奖励，折扣后到当前仍有 10 × 0.9^8 ≈ 4.3。
#     如果 gamma 太小（比如 0.1），8 步外的奖励几乎全折掉，智能体会"短视"——进阶实验可以改着玩。
#   · r_step=0.0：每步 0 分——这逼着它靠"到水井"才能拿分，不能靠"多走几步凑分"偷懒。
#
# 【看什么】打印出来的迷宫布局：S 起点、W 水井、X 陷阱、# 墙。对着它脑补"先上再右"的路线。
CONFIG = {
    "n_rows": 5, "n_cols": 5,
    "start": (4, 0),           # 起点：左下角
    "goal":  (0, 4),           # 水井：右上角，+10（要先上再右拐才能到 → 贪心陷阱的雷）
    "trap":  (2, 2),           # 陷阱：踩到 −10、本局结束
    "wall":  (1, 2),           # 墙：走不进去
    "r_goal": 10.0, "r_trap": -10.0, "r_step": 0.0,   # 到水井 +10 / 踩陷阱 −10 / 每走一步 0
    "max_steps": 50,           # 一局最多走几步（防止它绕圈不结束）
    "gamma": 0.9,              # 折扣因子 γ：看多远
}
ACTIONS = {0: (-1, 0), 1: (1, 0), 2: (0, -1), 3: (0, 1)}     # 0上 1下 2左 3右
ARROW_DXDY = {0: (0, -0.3), 1: (0, 0.3), 2: (-0.3, 0), 3: (0.3, 0)}

