# 实验 3 · 诊断：是过拟合，不是训练不够
# ============================================================================
# %% 3　诊断结论
# 【这段做什么】把实验 2 的三组证据归纳成一句精确的诊断，并讲透两个问题：
#   ① 为什么是"过拟合到训练分布"？  ② 为什么不是"训练不够"？
#   这段只有 print，没有新的实验代码——但它是整个 Class 3 逻辑链的"转折点"：
#   先看清问题的病根，才能对症下药（域随机化救回）。
#
# 【实验 2 三组证据的完整逻辑链】
#   实验 2-1：杆长 ≥1.0 → 标准模型崩      ← 物理结构变了，扛不住
#   实验 2-2：噪声 ≥0.2 → 标准模型崩      ← 观测被污染，扛不住
#   实验 2-3：重力/杆重/推力 大幅变化 → 仍 500  ← 量级缩放，扛住了
#   结论：PPO 不是对任何扰动都脆弱，而是专门对"训练时没见过"的改变脆弱——
#   这个模式就是"过拟合到训练分布"的特征。
#
# 【为什么不是"训练不够"——把这条路堵死】
#   实验 2-1 之后，你可能第一反应是：是不是训练步数不够，再多训几万步就好了？
#   不是。理由很直接：标准模型在标准世界已经满分 500，满分就是"学到头了"，
#   继续在同一个世界训根本没有改进空间。而且更关键的是——
#   即使再训 100 万步，训练环境还是标准 CartPole（length=0.5、无噪声），
#   它从来不会遇到 length=1.5 或 noise=0.2 的场景，当然学不到那些的应对方法。
#   缺的不是训练量，是【见过的经历种类】。
#   这和 Class 2 的"加训练局数救不了纯贪心"是同一种病：
#     Class 2 里 ε=0 多训多少步也救不了，因为缺的是"探索"这件事本身；
#     这里多训多少步也救不了，因为缺的是"见过扰动世界"这件经历本身。
#   训练量不是病根，见识（训练分布的覆盖范围）才是。
#
# 【"过拟合到训练分布"是什么意思——讲透】
#   "训练分布"= 训练时经历过的所有场景的集合。
#   标准训练的训练分布就只有 length=0.5、无噪声的场景——非常窄。
#   PPO 把神经网络调到在这个分布上表现最好。满分是真的，但那是"这个分布内的满分"。
#   一旦测试场景离这个分布很远（length=1.5），神经网络就到了"从没见过的地方"，
#   之前学的那套技巧对不上，性能就崩了。
#   这在机器学习里叫"过拟合（overfitting）"：在训练集上完美，在训练集外就失效。
#   RL 里的过拟合更隐蔽——loss 很低、reward 很高、曲线很好看，看起来一切正常，
#   但这些指标只反映了"在训练那个世界里"的表现，根本没有反映"泛化能力"。
#
# 【sim-to-real gap 是什么——接土箱项目】
#   你在仿真（simulation）里训练，把模型搬到真实（real）设备上用，中间这道鸿沟叫 sim-to-real gap。
#   这道沟里装的就是"仿真里有、现实里没有"或"现实里有、仿真里没有"的各种差异：
#     · 物理模型不精确（真实土箱的土压力响应和仿真里的不一样）
#     · 传感器噪声（电化学探头的 pA 级信号带噪声，仿真里是干净数字）
#     · 执行器延迟（真实电机有延迟，仿真里一般是理想即时响应）
#     · 未建模动态（土箱里的电化学反应有各种仿真没考虑到的非线性效应）
#   这节 CartPole 实验里，"杆长变化"对应"物理模型不精确"，"传感器噪声"直接对应。
#   你亲手看到了 sim-to-real gap 是怎么让一个仿真满分模型在现实里垮掉的——
#   这就是这节课的核心直觉，比看论文有感多了。
#
# 【下一步：对症下药】
#   既然病根是"只见过一种世界"，那就让它训练时"见过很多种世界"——
#   这就是域随机化（domain randomization），实验 4 马上去做。
print("=== 实验 3 诊断结论 ===")
print("· 现象：标准世界满分 500，杆长 1.5 只剩 16、噪声 0.2 只剩 162。")
print("· 不是训练不够：标准世界已满分（学到头了），它只是从没见过长杆/噪声的世界。")
print("· 病根：过拟合到训练分布——只在 length=0.5、无噪声的世界训，策略精调到这一组参数，换分布就失效。")
print("· 这就是 sim-to-real gap：仿真满分 ≠ 真实土箱能用。要救，就得让它训练时'见多识广'。")

