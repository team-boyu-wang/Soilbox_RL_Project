# 实验 2 · 诊断：是学习率/训练不够，还是别的？
# ----------------------------------------------------------------------------
# 【从实验 1 到实验 2 的过渡】
# 实验 1 得到一个让人不安的结果：ε=0，30/30 全军覆没，回报 0.00。
# 这时候最自然的第一反应是："是不是参数没调好？学习率 α 太小？训练局数太少？"
# 这正是科研里的"失败归因三问"中的第一问：是超参的锅吗？
#
# 如果你直接跳过这步、换成 ε-greedy，你是"知道答案→选对了方法"，
# 但你不理解为什么——如果换个问题，你还是会犯同样的错。
# 所以实验 2 先把"超参归因"这条路系统性地堵死：
#   固定 ε=0，只动 α 和 episodes，看结果动没动。
# 如果真是超参的锅，某个 α 组合应该能救回来；如果全是 0%，说明病根在别处。
#
# 这正是科研里的"失败归因"：撞见坏结果别急着换方法，先把"是不是参数"这条路堵死，
# 才能说清楚"我排除了 X，剩下唯一合理解释是 Y"——这是答辩/论文的标准表述。
# ============================================================================

# %% 2-1　ε=0 扫学习率 α + 加训练局数 → 全都救不回
# 【这段做什么】固定 ε=0，分两组分别扫：
#   ① 学习率 α ∈ {0.1, 0.5, 1.0}（覆盖"太保守"到"每次全信"三档）；
#   ② 训练局数 episodes ∈ {300, 1000, 3000}（覆盖"默认"到"10 倍"三档）。
#   看判据（成功率/回报）动不动。
#
# 【控制变量】ε 锁死=0，每次只改一个自变量（α 或 episodes），其余全不变。
#   这样如果有某一行结果变了，就能精确归因到那个变量。
#
# 【α 的各档直觉】
#   α=0.1：每步只挪 10% 的误差，"学得很慢"，但慢慢来也稳；
#   α=0.5：默认档，每步挪一半误差；
#   α=1.0：每步完全相信新估计，直接覆盖旧值（有时不稳定，但也许快）。
#   如果"太慢"是病根，α=1.0 应该救回来；结果它也是 0%，说明"慢"不是问题所在。
#
# 【预期（服务器实测）】不管 α 怎么调、训练加到 3000 局，成功率全是 0%、回报全是 0.00。
#   一点都没救回——这就是"病根不是参数"的硬证据，列出来放到诊断结论里。
#
# 【看什么】整张表的"成功率"列是不是全 0%，有没有任何一行例外。
#   如果有例外，说明参数真的有影响；如果全是 0%，可以安全地说"超参不是病根"。
print("实验 2 诊断：ε 锁死=0，只动学习率 / 训练局数，看能不能救回")
print("  【扫学习率 α】")
for al in [0.1, 0.5, 1.0]:
    s, ret = evaluate_seeds(eps=0.0, alpha=al)
    print(f"     α={al}: 成功率 {s*100:.0f}%  平均回报 {ret:.2f}")
print("  【加训练局数 episodes】")
for ep in [300, 1000, 3000]:
    s, ret = evaluate_seeds(eps=0.0, episodes=ep)
    print(f"     episodes={ep}: 成功率 {s*100:.0f}%  平均回报 {ret:.2f}")
print("  （服务器实测：以上全部 0%、0.00 —— 学习率、训练量都不是病根。）")

# %% 2-2　诊断结论：病根是【没探索】
# 【这段做什么】把 2-1 的系统性对照证据收成一句清晰的诊断结论，
#   并讲透"为什么纯贪心+全0表必然撞死、调参救不了"——这是要能讲给评委的核心逻辑。
#
# 【为什么调参救不了（完整逻辑链，能写进答辩的一段话）】
#   Q-learning 要"学"，前提是它得【撞到非 0 的奖励信号】——到水井 +10 或踩陷阱 −10，
#   才有非 0 的 target 去更新 Q 表，才有"学习材料"。
#
#   可纯贪心(ε=0)从全 0 表出发，argmax 永远选动作 0（"上"），
#   把自己锁死在"起点→左上角→撞墙原地"的死循环里，
#   从训练第 1 局到第 3000 局，【一次都没踏上过水井或陷阱】——它完全没有学习材料。
#
#   调大 α？α 是"每步朝误差挪多少"，可这里误差 = target − Q[s,a] = 0 − 0 = 0，
#   0 乘以任何 α 还是 0。有再大的学习率，但没有信号输入，等于拿了个高倍放大镜却没东西可看。
#
#   加训练局数？每一局都是完全相同的"左上角撞墙死循环"，跑 3000 局只是把同一幕戏重演 3000 遍，
#   没有任何新信息进来，Q 表不会有任何变化。
#
#   → 唯一的出路：逼它偶尔别那么"贪"，随机试一个没试过的动作，哪怕只是 10% 的概率。
#     只要有过一次"误打误撞走到水井"，Q 表就有了第一条学习材料，然后慢慢传播开。
#     这就是 ε-greedy 探索要做的事（实验 3）。
print("=== 实验 2 诊断结论 ===")
print("· 现象：ε=0 时，学习率 α 怎么调、训练加到 3000 局，成功率全是 0%。")
print("· 归因：纯贪心从全 0 表出发，argmax 永远选同一个动作 → 撞死在墙上 → 一次都没碰到奖励 →")
print("        没有学习材料；误差恒为 0，α 再大、局数再多也无米下锅。")
print("· 推论：病根是【没探索】。要救，就得逼它偶尔随机试一步 → 这正是 ε-greedy（实验 3）。")

# ============================================================================
# 实验 3 · ε-greedy 救：加一点探索
# ----------------------------------------------------------------------------
# 【从实验 2 到实验 3 的过渡】
# 实验 2 系统性地排除了"超参的锅"，指向了唯一的病根：没有探索。
# 诊断出病根之后，解法方向就很清晰了：给它一点探索，逼它偶尔走没走过的路，去撞到奖励。
#
# ε-greedy 是最简洁的探索策略：
#   · 以概率 (1-ε)：贪心——选当前 Q 最大的动作（利用已有知识）；
#   · 以概率 ε：随机——从所有动作里均匀抽一个（探索未知）。
#   一句话：大部分时候用学到的知识，偶尔随机试一下没试过的动作。
#
# 为什么这么简单的改动就能救活？
#   只要 ε > 0，就有非零概率走到水井（尤其早期 Q 表很差时，随机探索更容易误打误撞到达）。
#   一旦第一次到达水井，+10 的奖励会沿着那条路反向传播到前几步，把路上的 Q 值都往上拉。
#   被拉高的 Q 值让贪心策略下次更可能选择同一条好路，探索和利用相互加强，策略越来越优。
#
# 注意：ε 不是越大越好（实验 4 会量化），但只要"够用"（ε≥0.1），就能从 0% 一跃到 100%。
# ============================================================================

# %% 3-1　ε-greedy（ε=0.1）训练 + 手算一步 Q 更新印证公式
# 【这段做什么】两件事：
#   ① 先用代码复现讲稿那道手算题（旧 Q=2.0 → 新 Q=3.75），把更新公式用数字钉死，不再是抽象符号；
#   ② 用 ε=0.1 跑 evaluate_seeds，看救没救回来。
#
# 【手算题（讲稿 Slide 17-18）详细拆解】
#   场景：智能体在某状态做了某动作，旧估计 Q=2.0，这步拿到奖励 r=1.0，
#         新状态下最优动作的 Q 值 max_Q_next=5.0，折扣 γ=0.9，学习率 α=0.5。
#   第一步：算"新估计"（这步我实际该拿多少）：
#     target = r + γ × max_Q_next = 1.0 + 0.9 × 5.0 = 1.0 + 4.5 = 5.5
#   第二步：算"TD 误差"（新估计比旧估计高多少）：
#     error = target − old_Q = 5.5 − 2.0 = 3.5
#   第三步：挪一步（只挪一半误差，α=0.5）：
#     new_Q = old_Q + α × error = 2.0 + 0.5 × 3.5 = 2.0 + 1.75 = 3.75
#   为什么不直接跳到 5.5？α=0.5 意味着"只信一半新信息"——这避免了过度响应单次噪声。
#   就像你昨天估明天 20°，今天测到 27°，你不会立刻改口说"明天 27°"，可能修正为"大概 23° 左右"。
#
# 【预期（服务器实测）】ε=0.1 → 成功率 100%(30/30)、平均回报 10.00。
#   一加探索，立刻从 0 救到满分——这和实验 1 的 0% 形成最强对比，直接印证"病根=没探索"。
old_q, r, gamma, max_q_next, alpha = 2.0, 1.0, 0.9, 5.0, 0.5
new_estimate = r + gamma * max_q_next; error = new_estimate - old_q; new_q = old_q + alpha * error
print("实验 3：先用代码印证更新公式（讲稿那道手算题）")
print(f"  新估计 r+γ·maxQ' = {r}+{gamma}×{max_q_next} = {new_estimate} | 误差 {error} | 新 Q = {old_q}+{alpha}×{error} = {new_q}")
print(f"  → 3.75，和手算一致；没跳到 5.5 是因为 α=0.5 只挪了一半误差。\n")
eg_succ, eg_ret = evaluate_seeds(eps=0.1)
print(f"  加 ε-greedy（ε=0.1）后：成功率 {eg_succ*100:.0f}%（30 seed）  平均回报 {eg_ret:.2f}")
print("  （服务器实测：100%、10.00 —— 一加探索，立刻从 0 救到满分。）")

# %% 3-2　看 ε=0.1 学出来的路径 + 策略箭头 → 走出 8 步最优路
# 【这段做什么】两件事：
#   ① 打印 ε=0.1 学好的策略（rollout_greedy，不再探索）实际走的格子序列；
#   ② 用 plot_policy 把整张 Q 表画成"每格最优动作箭头图"，同时画 ε=0 和 ε=0.1 的对比。
#
# 【预期（服务器实测）】路径正好 8 步，和 BFS 理论最优完全一致：
#   (4,0)→(3,0)→(2,0)→(1,0)→(0,0)→(0,1)→(0,2)→(0,3)→(0,4)
#   即"先一路向上到顶、到达左上角 (0,0)，再右拐沿顶边走到水井 (0,4)"。
#   这条路不经过陷阱 (2,2)，也不走弯路，正是这迷宫里能走的最短路。
#
# 【为什么学到的是最优路而不是随便一条能到的路】
#   Q-learning 在 γ=0.9、足够多探索和训练的情况下，理论上会收敛到最优 Q 值（Q*）——
#   Q*(s,a) = "从状态 s 做动作 a，最优策略下折扣回报的期望值"。
#   贪心执行 Q* 就得到最优策略。8 步路折扣回报 = 10 × 0.9^8 ≈ 4.3 到当前；
#   更长的路折扣更多，所以 Q* 天然鼓励走短路——折扣因子 γ 就是"不喜欢绕圈"的内置动力。
#
# 【两张策略图的对比含义】
#   ε=0 图：几乎全格箭头死板朝上（全 0 表的 argmax=0="上"），撞墙格还在指墙。
#   ε=0.1 图：箭头形成清晰的"先上后右"路线，水井周边格子已经学到"指向水井"，陷阱旁边的格子也学到了绕开。
#   这两张图放在一起，就是"探索 vs 利用"最直观的视觉铁证。
#
# 【看什么】路径末尾是不是水井 (0,4)、步数是不是 8（= BFS 最优）；
#   箭头图里是不是能看出一条"先上再右"的清晰通道，ε=0 图是不是几乎全是朝上的死路。
Q_eg = train(eps=0.1, seed=0)
eg_outcome, eg_G, eg_path = rollout_greedy(Q_eg)
print("实验 3：ε=0.1 学出来的策略，实际走的路径——")
print("  " + " → ".join(str(p) for p in eg_path))
print(f"  结局={eg_outcome}, 回报={eg_G:.2f}, 共 {len(eg_path)-1} 步（BFS 理论最优={OPT_STEPS} 步）。")
