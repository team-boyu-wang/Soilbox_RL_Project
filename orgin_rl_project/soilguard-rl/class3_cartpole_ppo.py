plt.xlabel("pole length (test world)"); plt.ylabel("avg steps survived (max 500)")
plt.title("Robustness: standard overfits to length=0.5, DR generalizes")
plt.legend(); plt.grid(alpha=0.3); plt.tight_layout(); plt.show()
print("鲁棒性曲线：红线（标准）在杆长>1 后跳水，绿线（域随机化）全程满分。")
print("→ 标准模型过拟合到训练那一点；域随机化模型在整段杆长区间都能用。这才叫'能用'。")

