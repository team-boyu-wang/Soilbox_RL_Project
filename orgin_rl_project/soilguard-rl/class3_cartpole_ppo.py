# %% 2-1　只改杆长 → 标准模型暴跌
# 【这段做什么】把训练好的标准模型，丢进"杆长不同"的一系列世界里测——
#   从最短的 length=0.25 到最长的 length=2.0，逐一测成绩，看它还能不能撑住。
#   其它所有参数（重力、杆重、推力、噪声）全锁死在默认值，绝对不动。
#
# 【控制变量：为什么只改杆长、其他全不动】
#   这是"控制变量实验"最关键的一步：如果你同时改杆长和重力，看到成绩掉了，
#   你没法说清是杆长害的还是重力害的——两个变量都变了，成绩的变化没法归因。
#   只改一个，其余锁死，成绩的变化只有一种解释。这在论文里叫做"单因素消融实验"。
#
# 【为什么杆长会害它垮——直觉】
#   PPO 训练时一直面对 length=0.5 的杆。这根杆的平衡点、摆动频率、惯性特性
#   共同决定了"每步推多大力才合适"。训练 5 万步下来，神经网络对这些"节奏"
#   已经适应得非常精准——但这个精准是专门针对 length=0.5 的。
#   换成 length=1.5：长杆的摆动更慢（惯性更大）、平衡点的物理响应完全不同，
#   需要的推力节奏也变了。神经网络还按着"0.5 的节奏"出动作，自然就失调了。
#   就像一个节拍器校准到 120bpm、用来指挥 60bpm 的曲子——全对不上。
#
# 【预期（服务器实测）】
#   0.25→500, 0.5→500, 0.75→500, 1.0→83.6, 1.5→16.4, 2.0→19.0
#   杆长 ≤0.75 还撑得住（短杆误差容忍度更大），一旦 ≥1.0 直接崩——从满分掉到几十分甚至十几分。
#   特别是 1.5 只剩 16.4 步、2.0 只剩 19.0 步，这不是"差一点"，而是"完全不会了"。
#
# 【看什么】
#   · 控制台输出里，杆长 ≤0.75 的那几行没有"← 崩了"标记；1.0 开始就有了。
#   · 留意这个"断崖"发生在哪里——不是线性下降，而是在某个阈值附近突然跌落。
#   · 这就是"训练好≠能用"的第一个铁证：同一个模型，同一个任务（平衡杆），
#     只是换了一根稍长的杆，就从满分变成只撑十几步。
print("实验 2-1：把满分模型丢进'杆长不同'的世界（只改杆长）")
lengths = [0.25, 0.5, 0.75, 1.0, 1.5, 2.0]
std_by_len = []
for L in lengths:
    s = evaluate(std_model, (lambda L=L: make_tweaked(length=L)))
    std_by_len.append(s)
    flag = "" if s > 450 else "  ← 崩了"
    print(f"  杆长 length={L:<4} 平均撑 {s:6.1f} 步{flag}")
print("  → 杆长一过 1.0，满分模型直接崩（服务器实测 1.5 只剩 16.4）。它没学会'平衡'，只学会'平衡这根特定的杆'。")

# %% 2-2　只加噪声 → 标准模型也暴跌
# 【这段做什么】杆长锁回默认 0.5（和训练时完全一样），改成给观测加传感器高斯噪声来测。
#   和上一组实验一样只改一个变量——这次只改 obs_noise，杆长/重力/杆重/推力全不动。
#
# 【为什么要测噪声——对你的项目极度重要】
#   仿真里的"观测"是精确的数字：位置精确到小数点后 N 位，速度也是。
#   但真实世界的传感器永远有误差：编码器有量化误差、陀螺仪有温漂、ADC 有底噪……
#   你的土箱项目里，电化学噪声探头读出来的 pA 级电流信号更是噪声重灾区：
#   基线漂移、电极界面的热噪声、外界电磁干扰……都会叠加在观测上。
#   仿真里训到满分的策略，一旦搬到真实探头上，观测就从"干净信号"变成了"脏信号"。
#   这一组实验就是在 CartPole 层面预演这件事：看看"观测一脏，策略崩不崩"。
#
# 【为什么加高斯噪声会害它垮——直觉】
#   神经网络在训练时接收的观测全是干净的，它学到的策略本质上是：
#   "看到某个精确的位置/速度/角度组合，就推某个方向"。
#   加了噪声后，同一个物理状态，观测值每次都微微不一样——
#   神经网络看到的输入已经不是它"认识"的模式了，输出的动作就开始出错。
#   噪声越大，输入越"陌生"，出错越多，杆越快倒。
#   就像一个近视眼摘了眼镜、模糊地看着杆子来平衡——越模糊越难。
#
# 【预期（服务器实测）】
#   0→500, 0.05→500, 0.1→479.7, 0.2→162.0, 0.5→44.3
#   小噪声（0.05）还能扛住；一旦噪声标准差达到 0.2，成绩就从 500 跌到 162（剩 1/3）；
#   0.5 时只剩 44，已经基本不会平衡了。
#   特别注意：0.1→479.7 还差不多，0.2→162 就开始显著崩——存在一个噪声"耐受阈值"。
#
# 【看什么】
#   · 输出里 noise=0.1 那行可能已经有"← 崩了"，noise=0.2 肯定有。
#   · 结合上一组：标准模型对"杆长变化"和"传感器噪声"都很脆弱，说明它对训练分布
#     的依赖不只是物理结构层面，连"观测的精度"都要和训练时一样才行——非常脆。
#   · 这就是实验 2-1 和 2-2 合起来的结论：既扛不住结构变化，也扛不住观测污染。
print("实验 2-2：给观测加传感器噪声（只改 noise，杆长锁回默认）")
noises = [0.0, 0.05, 0.1, 0.2, 0.5]
std_by_noise = []
for ns in noises:
    s = evaluate(std_model, (lambda ns=ns: make_tweaked(obs_noise=ns)))
    std_by_noise.append(s)
    flag = "" if s > 450 else "  ← 崩了"
    print(f"  噪声 noise={ns:<5} 平均撑 {s:6.1f} 步{flag}")
print("  → 传感器一抖（noise≥0.2）也崩（服务器实测 0.2 只剩 162）。这正是真实土箱探头会遇到的坎。")

# 画实验 2 的两条暴跌曲线
