axes[0].plot(lengths, std_by_len, "o-", color="red"); axes[0].axhline(500, ls="--", color="gray", alpha=0.5)
axes[0].set_xlabel("pole length"); axes[0].set_ylabel("avg steps (max 500)")
axes[0].set_title("Standard model vs pole length (cliff!)"); axes[0].grid(alpha=0.3)
axes[1].plot(noises, std_by_noise, "o-", color="purple"); axes[1].axhline(500, ls="--", color="gray", alpha=0.5)
