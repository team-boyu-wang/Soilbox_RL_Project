print("实验 1：纯贪心 ε=0（只利用、不探索）")
print(f"  到水井成功率 = {g0_succ*100:.0f}%（30 seed）   平均回报 = {g0_ret:.2f}")
print(f"  对照标准答案：BFS 最优 {OPT_STEPS} 步、满分回报 10.0 —— 它却 0 分。（服务器实测：0%，0.00）")
print("  → 一个理论上'能靠试错学会'的算法，配上纯贪心，30 次一次都没到水井。为什么？看下一段它走的路。")

# %% 1-3　看 ε=0 学出来的路径 → 撞死在左上角的”死循环现场”
# 【这段做什么】把 ε=0 训练好的 Q 表，用 rollout_greedy 跑一局，打印它真实走过的格子序列。
# 【为什么看路径（不只看分数）】光知道”0 分”，你知道它失败了，但不知道它是”学了个错误策略”
#   还是”根本没动”。看路径就一目了然——是在哪卡死、是卡在同一个格子重复还是乱窜。
#
# 【预期（服务器实测）】路径一路向上到左上角，然后死死撞墙、原地重复 (0,0) 直到超时：
#   (4,0)→(3,0)→(2,0)→(1,0)→(0,0)→(0,0)→(0,0)→…（打印前 12 步就能看出规律）
#
# 【为什么会这样（把整个死循环讲透，能对评委说清楚）】
#   初始 Q 表全 0 → 每个状态每个动作都”以为一样好”。
#   argmax([0,0,0,0]) 返回下标 0，动作 0 = “上”。所以第一步：(4,0) 选上→(3,0)。
#   (3,0) 的 Q 也全 0，还是选”上”→(2,0)。以此类推走到 (0,0)（左上角）。
#   在 (0,0) 选”上”：边界外，撞墙，原地不动，pos 仍 (0,0)，r=0，s2=s。
#   Q 更新：target = 0 + 0.9×max(Q[(0,0)]) = 0；误差=0-0=0；Q[(0,0),0] 不变，还是 0。
#   下一步还是选”上”，还是撞墙，还是不变……无限循环，直到 max_steps=50 到上限超时。
#   关键问题：为什么 Q 表其他动作(下/左/右)没有机会被更新？
#   因为纯贪心永远选同一个动作(上)，其他动作的 Q 值从来没被触发更新过——它们一直是 0，
#   但”上”也是 0，所以 argmax 还是选”上”。这就是”没探索 → 只用一个动作 → 锁死”的完整逻辑链。
#
# 【看什么】路径末尾是不是一串重复的 (0,0)，以及它有没有哪怕一次踏上(0,1)或往右走的格子。
g0_outcome, g0_G, g0_path = rollout_greedy(train(eps=0.0, seed=0))
print("实验 1 死亡现场：ε=0 学出来的策略，实际走的路径——")
print("  " + " → ".join(str(p) for p in g0_path[:12]) + "  …（之后一直重复左上角到超时）")
print(f"  结局={g0_outcome}, 回报={g0_G:.2f}。它一路向上撞死在左上角 (0,0)，从没拐向水井。")
print("  病根：全 0 表 → argmax 永远选'上' → 撞墙奖励 0、Q 永远不变 → 锁死在'对墙一直上'的死循环。")

