# %% 0-3　GridWorld 环境（reset/step）+ BFS 理论最优（标准答案）
# 【这段做什么】① 写 GridWorld（reset/step，纯 numpy 手搓）；② 用 BFS 算"起点到水井最短几步"——
#   这是不靠学习、纯数学算出来的【理论最优】，后面拿它当"满分标准答案"，给 Q-learning 学到的策略打分。
#
# 【GridWorld 的两个核心接口（和 gym 一样的约定）】
#   · reset()：把智能体扔回起点，返回初始状态编号 s。
#     状态编号 s = 行×列数 + 列，比如 (0,4)（右上角水井）的编号 = 0×5+4 = 4。
#     共 5×5=25 个状态（0..24），Q 表就是 (25, 4) 的矩阵。
#   · step(a)：做动作 a（0上/1下/2左/3右），返回 (新状态 s2, 奖励 r, 是否结束 done, 结局 info)。
#     撞墙或撞边界：原地不动（s2 = s），但仍算一步、r=0——所以纯贪心撞墙能原地死循环。
#
# 【为什么先算理论最优（BFS 的意义）】
#   科研里评估一个方法，需要一个"满分参照"作为上界。BFS（广度优先搜索）不靠学习，
#   纯粹按最短路算法遍历所有可能路径，给出起点到水井的最短步数 = 这迷宫里任何策略的理论上限。
#   服务器实测 = 8 步。Q-learning 学到的策略到底有多好，和它一对账就知道（第 5 部分）。
#   如果 Q-learning 也走出 8 步，说明它学到了真正最优；多于 8 步说明还有改进空间。
#
# 【BFS 为什么绕开陷阱】bfs_optimal_steps 的 blocked 集合包含了 wall 和 trap——
#   BFS 求的是"不踩陷阱的最短路"，因为踩陷阱立刻结束且扣 10 分，这不算"到水井"。
#   所以 8 步路径绕开了陷阱(2,2)，代价是比"斜线穿越"多走了几步。
#
# 【看什么】BFS 算出的最短步数（服务器实测 = 8 步）。你可以自己在布局图上数一遍验证。
class GridWorld:
    """5×5 网格世界。状态=格子编号(0..24)；动作=上下左右(0..3)。
    到水井 +10 结束、踩陷阱 −10 结束、每步 0 分。撞墙/撞边界=原地不动（仍算一步）。"""
    def __init__(self, c=CONFIG):
        self.c = c; self.R, self.C = c["n_rows"], c["n_cols"]
        self.nS, self.nA = self.R * self.C, 4
        self.walls = {c["wall"]}; self.trap = c["trap"]; self.goal = c["goal"]
    def sid(self, rc): return rc[0] * self.C + rc[1]
    def reset(self): self.pos = self.c["start"]; self.t = 0; return self.sid(self.pos)
    def step(self, a):
        dr, dc = ACTIONS[a]; nr, nc = self.pos[0] + dr, self.pos[1] + dc
        if 0 <= nr < self.R and 0 <= nc < self.C and (nr, nc) not in self.walls:
            self.pos = (nr, nc)                       # 撞墙/边界则留在原地
        self.t += 1
        if self.pos == self.goal: return self.sid(self.pos), self.c["r_goal"], True, "goal"
        if self.pos == self.trap: return self.sid(self.pos), self.c["r_trap"], True, "trap"
        done = self.t >= self.c["max_steps"]
        return self.sid(self.pos), self.c["r_step"], done, ("timeout" if done else None)

def bfs_optimal_steps(c=CONFIG):
    """BFS 求起点到水井的最短步数（避开墙和陷阱）= 这迷宫的理论最优，当标准答案。"""
    blocked = {c["wall"], c["trap"]}
    q = deque([(c["start"], 0)]); seen = {c["start"]}
    while q:
        (r, col), d = q.popleft()
        if (r, col) == c["goal"]: return d
        for dr, dc in ACTIONS.values():
            nr, nc = r + dr, col + dc
            if 0 <= nr < c["n_rows"] and 0 <= nc < c["n_cols"] and (nr, nc) not in blocked and (nr, nc) not in seen:
                seen.add((nr, nc)); q.append(((nr, nc), d + 1))
    return None

OPT_STEPS = bfs_optimal_steps(CONFIG)
print(f"BFS 理论最优：起点到水井最短 {OPT_STEPS} 步（避开墙和陷阱）——这是标准答案，服务器实测=8。")

