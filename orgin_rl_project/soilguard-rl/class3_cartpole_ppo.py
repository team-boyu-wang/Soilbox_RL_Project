# %% 0-3　判据写成代码：evaluate() + 训练函数
# 【这段做什么】定两个核心工具：
#   ① evaluate(model, env_fn, n=30)：判据函数——把模型丢进 env_fn() 造的世界跑 n 局，
#      返回平均撑了多少步（= 平均累计回报）。这是量化"换个世界还能不能用"的硬尺子。
#   ② train_ppo(env_fn, steps, tag)：在某个世界里训一个 PPO，返回模型 + 训练曲线。
#   还有一个辅助工具 RewardLogger：回调函数，记录训练过程中每个 rollout 的平均奖励，
#   用来画"训练曲线"——RL 的体温计，往上爬说明在学、平了说明收敛了、抖说明不稳定。
#
# 【判据函数化的意义——为什么不能凭肉眼看一局】
#   同一个模型跑一局可能因初始状态不同偏差很大：运气好的局能到 500，运气差的局可能
#   几十步就倒。30 局平均才能消掉这个随机性，给出稳定的"真实水平"。
#   这和 Class 2 的"30 个随机 seed 全测"是同一种科研习惯：单次结果可能是噪声，
#   多次统计才是信号。把判据写成函数（而不是散落各处的一次性代码），还有一个好处：
#   整个文件里任何地方要测某个模型，调一次 evaluate 就行，不会漏步骤、不会错误地
#   "某次测用了不同 seed"。判据一致，结论才可比。
#
# 【为什么 evaluate 传 env_fn（造环境的函数）而不是一个固定的环境对象】
#   因为我们要在【各种不同的世界】里测同一个模型：
#   标准世界（make_standard）、杆长 1.5 的世界（lambda: make_tweaked(length=1.5)）、
#   噪声 0.2 的世界（lambda: make_tweaked(obs_noise=0.2)）……
#   如果传固定环境对象，每次测不同世界就要在外面重新建环境再传进来，很繁琐。
#   传"造环境的函数"，evaluate 内部自己调用一次，想测哪个世界就传哪个工厂函数——
#   这是"工厂模式"的简单应用，也是让判据可复用的关键设计。
#
# 【控制变量在评估环节的体现】
#   evaluate 里每局用固定 seed（2000+ep，ep 从 0 到 n-1），保证不同模型在
#   【完全相同的 30 个初始局面】上比。如果各局的初始位置和速度都随机不一样，
#   你就不能直接说"A 模型比 B 模型撑得久"——也许只是 A 运气好初始局面更容易。
#   固定评估 seed 就是消除这个"运气差异"，让成绩差异只来自模型本身，干净。
#
# 【PPO 三行核心是什么（先理解再看代码）】
#   train_ppo 里只有三行真正"跑了 RL"：
#     1. model = PPO("MlpPolicy", env, ...)   ← 建一个"用 MLP 神经网络当大脑"的 PPO 智能体
#     2. model.learn(total_timesteps=steps)   ← 让它和环境互动 steps 步，不断收集经验、更新网络
#     3. model.predict(obs)                   ← （在 evaluate 里）用训练好的网络预测当前最优动作
#   其余都是监控（Monitor、RewardLogger）——Monitor 是 SB3 要求的，让 ep_info_buffer 能记录
#   每局的总回报，RewardLogger 再把这些数据抓下来画成训练曲线。
#
# 【看什么】运行这段不会有输出，只是把两个工具函数装进内存。
#   这段是"造工具"；实验 1~4 才是"用工具"。
class RewardLogger(BaseCallback):
    """记录训练过程中每个 rollout 的平均回合奖励，用来画训练曲线（RL 的'体温计'）。"""
    def __init__(self): super().__init__(); self.ts, self.rew = [], []
    def _on_step(self): return True
    def _on_rollout_end(self):
        buf = self.model.ep_info_buffer
        if buf and len(buf) > 0:
            self.ts.append(self.num_timesteps)
            self.rew.append(float(np.mean([e["r"] for e in buf])))

def make_standard():
    """造一个标准 CartPole（训练用的世界）。"""
    return gym.make("CartPole-v1")

def make_tweaked(length=0.5, obs_noise=0.0):
    """造一个'改了某参数'的 CartPole（测试用的扰动世界）。"""
    return TweakCartPole({"length": length}, obs_noise=obs_noise)

def evaluate(model, env_fn, n=30):
    """判据：把 model 丢进 env_fn() 造的世界跑 n 局，返回平均撑的步数（= 平均回报）。"""
    env = env_fn(); scores = []
    for ep in range(n):
        obs, _ = env.reset(seed=2000 + ep)
        done, G = False, 0.0
        while not done:
            a = int(model.predict(obs, deterministic=True)[0])   # 部署时用确定性动作，不再探索
            obs, r, term, trunc, _ = env.step(a)
            G += r; done = term or trunc
        scores.append(G)
    env.close(); return float(np.mean(scores))

def train_ppo(env_fn, steps, tag=""):
    """在 env_fn() 造的世界里训一个 PPO，返回 (模型, 训练曲线记录器)。"""
    env = Monitor(env_fn())
    model = PPO("MlpPolicy", env, seed=SEED, verbose=0, device="cpu")   # 三行核心之一：建模型
    lg = RewardLogger()
    print(f"  开始训练 PPO（{tag}，{steps} 步，CPU 几分钟，耐心等）...")
    model.learn(total_timesteps=steps, callback=lg)                     # 三行核心之二：开训
    return model, lg

print("判据流水线就绪：evaluate(换个世界测撑多久) + train_ppo(在某世界里训)。")

