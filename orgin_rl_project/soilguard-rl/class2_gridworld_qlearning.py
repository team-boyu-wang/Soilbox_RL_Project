# 研究问题：Q-learning 配纯贪心(ε=0，每步只选当前 Q 最大的动作)，能不能学会走到水井？
# 自变量：探索率 ε（实验 1 先固定 ε=0）。
# 因变量/判据（见 1-1）：① 到水井成功率；② 平均回报。对照基准：BFS 最优 8 步、回报 10。
