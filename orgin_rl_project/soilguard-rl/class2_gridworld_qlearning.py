# 实验 4 · 判据量化：探索要多少（扫 ε）
# ----------------------------------------------------------------------------
# 【从实验 3 到实验 4 的过渡】
# 实验 3 证明了"ε=0.1 就能救回来"——但这引出一个新问题：探索要多少才够？
# ε=0 → 死；ε=0.1 → 满分。那 ε=0.05 呢？ε=0.2 呢？探索越多越好吗？
#
# 实验 4 做的事：把 ε 当作"旋钮"，系统性地扫一排（0 → 0.05 → 0.1 → 0.2 → 0.3），
# 用判据（成功率/回报）量化每个 ε 的表现，画出"探索量 → 学得多好"的曲线。
# 这是把"探索 vs 利用"从一句口号，变成一条能放进论文的定量曲线。
#
# 也注意：ε 不是越大越好。ε 很大时，智能体花太多时间随机走，"利用"的比例不够，
# 可能学得慢（虽然这个简单迷宫上 ε=0.3 还没到问题区）。真实项目常用 ε 衰减：
# 早期 ε 大（多探索，快速发现奖励），后期 ε 小（多利用，精细化策略）——这是后续课的内容。
# ============================================================================

# %% 4-1　扫 ε（0~0.3）判据表 + 曲线
# 【这段做什么】对 sweep_eps = [0.0, 0.05, 0.1, 0.2, 0.3] 这五个 ε，
#   各自跑 evaluate_seeds（30 seed），记录成功率和平均回报，打成表格并画成曲线。
#
# 【控制变量】只有 ε 在变，迷宫/γ/α/局数（300 局）全锁死，才能把曲线的形状归因到"探索量"。
#
# 【预期（服务器实测，必须和你跑出来的对上）】
#   ε=0.0  → 平均回报 0.00   (0/30 到水井)  ← 贪心陷阱死区
#   ε=0.05 → 平均回报 4.33  (13/30 到水井)  ← 临界区：13 个种子探索到了水井，17 个还没
#   ε=0.1  → 平均回报 10.00 (30/30 到水井)  ← 刚好够了：全部学会、都走最优路
#   ε=0.2  → 平均回报 10.00 (30/30 到水井)  ← 再多也行，这个迷宫不惩罚多探索
#   ε=0.3  → 平均回报 10.00 (30/30 到水井)  ← 同上
#
# 【ε=0.05 为什么是"临界区"】
#   ε=0.05 意思是"每步有 5% 概率随机走"。在 300 局里，平均每局 ~50 步（算上卡墙），
#   大约有 50×0.05=2.5 次随机探索。这很少——有些种子恰好探索到了通往水井的路，有些没有。
#   ε=0.1 时每局平均 5 次随机，探索够多，30 个种子都能找到水井。
#   这就是"临界"的来历：不是 0 或 1 的开关，而是有个从死到活的过渡区间。
#
# 【看什么】曲线的"转折点"在哪：ε=0 趴着、ε=0.05 爬坡、ε=0.1 到顶——这条台阶形状就是"最少够多少探索"的答案。
print("实验 4：扫 ε（探索量），看判据怎么变")
sweep_eps = [0.0, 0.05, 0.1, 0.2, 0.3]; sweep_succ = []; sweep_ret = []
for e in sweep_eps:
    s, ret = evaluate_seeds(eps=e)
    sweep_succ.append(s*100); sweep_ret.append(ret)
    print(f"   ε={e:<4} 成功率 {s*100:5.0f}%   平均回报 {ret:6.2f}")
fig, ax1 = plt.subplots(figsize=(7, 4))
ax1.plot(sweep_eps, sweep_ret, "o-", color="green"); ax1.set_xlabel("exploration rate epsilon")
ax1.set_ylabel("avg return", color="green"); ax1.axhline(10, ls="--", color="gray", alpha=0.6)
ax1.set_title("Exploration vs performance (0 -> too greedy, dies)")
ax1.grid(alpha=0.3); plt.tight_layout(); plt.show()
print("  曲线左端(ε=0)趴在 0、右端(ε≥0.1)顶到满分 10 —— 这就是'探索 vs 利用'的代码版铁证。")

# %% 4-2　解读：探索的"量"也有讲究
# 【这段做什么】把扫 ε 的结论收口，提炼出"探索 vs 利用"这条纪律的定量版本。
#
# 【三档含义，能说给评委】
#   ① ε=0：完全不探索 → 瘫痪(0 分)。这是这节最狠的对照——一个理论上能学会的算法，
#      只要切断探索，立刻满盘皆输。
#   ② ε=0.05：探索太少 → 13/30 的种子撞到了奖励(回报 4.33)，另外 17/30 还困在死循环里。
#      "临界区"不是好地方——你不知道你在的项目是哪一半，结果随机性很大。
#   ③ ε≥0.1：探索够了 → 30/30 全部学到最优(回报 10.0)，和 BFS 最优路 8 步完全一致。
#
# 【更深一层：为什么不让 ε 一直大？】
#   ε 大意味着更多时间在随机走而不是利用已知的好策略。对这个简单迷宫，ε=0.3 还没有
#   明显副作用；但在复杂任务或回报稀疏的环境里，ε 太大会导致"探索太多、收敛慢"。
#   真实 RL 项目的常见做法是"ε 衰减"（epsilon decay）：
#     · 训练初期：ε 大（比如 0.9），大量探索，快速发现哪条路有奖励；
#     · 训练后期：ε 逐渐降到 0.01，主要利用学好的策略，精细化。
#   这是"探索 vs 利用"不是 0/1 开关、而是动态配比的旋钮的最典型体现，也是后续课会涉及的内容。
#
# 【和 GeoTongue / SoilGuard 课题的联系（如果你会提到）】
#   这条"方法在你的数据上到底行不行，要用判据验证"的纪律贯穿所有课：
#   GeoTongue L2 里 GW 理论很优美但在独立词空间退化 → 判据揭露 → 换 Procrustes；
#   这里 Q-learning 理论上能学但没探索就死 → 判据揭露 → 加 ε-greedy。
#   同一套思路：不信名气，信判据。
print("=== 实验 4 解读 ===")
print("· ε=0 完全不探索 → 瘫痪(0)；ε=0.05 探索太少 → 半数救不回(4.33)；ε≥0.1 探索够 → 全部学到最优(10)。")
print("· 探索不是 0/1 开关，是要配比的旋钮：太少学不动、够了就好。真实项目常用 ε 衰减(早探索晚利用)。")

